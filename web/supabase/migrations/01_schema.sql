-- Personal single-user tool: flags are global and writable by anon.
CREATE POLICY "Allow public read access on repo_flags"
    ON repo_flags FOR SELECT TO public USING (true);

CREATE POLICY "Allow public insert on repo_flags"
    ON repo_flags FOR INSERT TO public
    WITH CHECK (github_id IS NOT NULL AND flag IN ('saved', 'hidden'));

CREATE POLICY "Allow public delete on repo_flags"
    ON repo_flags FOR DELETE TO public
    USING (github_id IS NOT NULL AND flag IN ('saved', 'hidden'));
